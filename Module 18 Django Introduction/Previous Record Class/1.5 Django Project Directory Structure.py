# DJANGO PROJECT FOLDER STRUCTURE


# __init__.py :
# The folder which contains __init__.py file is considered as python package.

# wsgi.py :
# WSGI (Web Server Gateway Interface) is a specification that describes
# how a web server communicates with web applications, synchronous.

# asgi.py :
# Asynchronous Server Gateway Interface.
# ASGI provides standard for both asynchronous and synchronous

# settings.py :
# This file contains all the information or data about project settings.
# E.g.:- Database Config information, Template, Installed Application, Validators etc.

# urls.py :
# contains information of url attached with application.

# manage.py :
# manage.py is a project-specific command-line utility



